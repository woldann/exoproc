// Nashorn scripts for Minecraft main-thread execution
// These run INSIDE the JVM's Nashorn engine and use obfuscated names via reflection
// They are separate from daemon eval scripts which have access to the mapping proxy

/**
 * Helper to find the Minecraft singleton instance via reflection.
 * Returns a Nashorn code block that sets `mc` variable.
 */
const MC_SINGLETON_FINDER = [
  'var mcCls = Java.type(__mcClassName__);',
  'var mc = null;',
  'var clsMethods = mcCls.class.getDeclaredMethods();',
  'for (var i = 0; i < clsMethods.length; i++) {',
  '  var m = clsMethods[i];',
  '  if (java.lang.reflect.Modifier.isStatic(m.getModifiers())',
  '      && m.getParameterTypes().length === 0',
  '      && m.getReturnType() == mcCls.class) {',
  '    m.setAccessible(true);',
  '    mc = m.invoke(null);',
  '    break;',
  '  }',
  '}',
  'if (!mc) return JSON.stringify({ success: false, error: "Cannot find Minecraft singleton" });',
].join('\n');

/**
 * Helper to find addScheduledTask (method taking Runnable).
 * Assumes `mc` variable is already set.
 * Sets `taskMethod` variable.
 */
const FIND_SCHEDULED_TASK = [
  'var taskMethod = null;',
  'var _c = mc.getClass();',
  'while (_c != null) {',
  '  var _ms = _c.getDeclaredMethods();',
  '  for (var _i = 0; _i < _ms.length; _i++) {',
  '    if (_ms[_i].getParameterTypes().length == 1 && _ms[_i].getParameterTypes()[0] == java.lang.Runnable.class) {',
  '      taskMethod = _ms[_i];',
  '      break;',
  '    }',
  '  }',
  '  if (taskMethod) break;',
  '  _c = _c.getSuperclass();',
  '}',
].join('\n');

/**
 * Helper to find the currentScreen field on Minecraft.
 * A field whose type (in its hierarchy) has a List field is assumed to be GuiScreen.
 * Assumes `mc` is set. Sets `currentScreen` and `scrField`.
 */
const FIND_CURRENT_SCREEN = [
  'var currentScreen = null;',
  'var scrField = null;',
  'var _fc = mc.getClass();',
  'while (_fc != null) {',
  '  var _ffs = _fc.getDeclaredFields();',
  '  for (var _fi = 0; _fi < _ffs.length; _fi++) {',
  '    var _f = _ffs[_fi];',
  '    if (java.lang.reflect.Modifier.isStatic(_f.getModifiers())) continue;',
  '    _f.setAccessible(true);',
  '    try {',
  '      var _val = _f.get(mc);',
  '      if (_val == null) continue;',
  '      var _vc = _val.getClass();',
  '      while (_vc != null) {',
  '        var _vfs = _vc.getDeclaredFields();',
  '        for (var _vi = 0; _vi < _vfs.length; _vi++) {',
  '          if (java.util.List.class.isAssignableFrom(_vfs[_vi].getType())) {',
  '            currentScreen = _val;',
  '            scrField = _f;',
  '            break;',
  '          }',
  '        }',
  '        if (currentScreen) break;',
  '        _vc = _vc.getSuperclass();',
  '      }',
  '    } catch(e) {}',
  '    if (currentScreen) break;',
  '  }',
  '  if (currentScreen) break;',
  '  _fc = _fc.getSuperclass();',
  '}',
].join('\n');

/**
 * Nashorn script to close the current GUI screen via displayGuiScreen(null).
 * Bindings required: __mcClassName__ (obfuscated Minecraft class name)
 */
export const NASHORN_CLOSE_SCREEN = [
  '(function() {',
  MC_SINGLETON_FINDER,
  '',
  '  // Find displayGuiScreen: void method, 1 param, non-primitive, non-Runnable, non-String, non-Object',
  '  // The param type must have a List field in its hierarchy (GuiScreen marker)',
  '  var displayMethod = null;',
  '  var c = mc.getClass();',
  '  while (c != null) {',
  '    var ms = c.getDeclaredMethods();',
  '    for (var i = 0; i < ms.length; i++) {',
  '      var m = ms[i];',
  '      var params = m.getParameterTypes();',
  '      if (params.length == 1',
  '          && !params[0].isPrimitive()',
  '          && params[0] != java.lang.Runnable.class',
  '          && params[0] != java.lang.String.class',
  '          && params[0] != java.lang.Object.class',
  '          && m.getReturnType() == java.lang.Void.TYPE) {',
  '        var pc = params[0];',
  '        var isScreen = false;',
  '        while (pc != null) {',
  '          var pfs = pc.getDeclaredFields();',
  '          for (var j = 0; j < pfs.length; j++) {',
  '            if (java.util.List.class.isAssignableFrom(pfs[j].getType())) { isScreen = true; break; }',
  '          }',
  '          if (isScreen) break;',
  '          pc = pc.getSuperclass();',
  '        }',
  '        if (isScreen) { displayMethod = m; break; }',
  '      }',
  '    }',
  '    if (displayMethod) break;',
  '    c = c.getSuperclass();',
  '  }',
  '',
  FIND_SCHEDULED_TASK,
  '',
  '  if (displayMethod) {',
  '    displayMethod.setAccessible(true);',
  '    if (taskMethod) {',
  '      taskMethod.setAccessible(true);',
  '      taskMethod.invoke(mc, new java.lang.Runnable({ run: function() {',
  '        try { displayMethod.invoke(mc, null); } catch(e) { e.printStackTrace(); }',
  '      }}));',
  '    } else {',
  '      displayMethod.invoke(mc, null);',
  '    }',
  '    return JSON.stringify({ success: true, message: "Screen closed" });',
  '  } else {',
  '    // Fallback: null out currentScreen field',
  FIND_CURRENT_SCREEN,
  '    if (scrField) {',
  '      if (taskMethod) {',
  '        taskMethod.setAccessible(true);',
  '        taskMethod.invoke(mc, new java.lang.Runnable({ run: function() {',
  '          try { scrField.set(mc, null); } catch(e) {}',
  '        }}));',
  '      } else {',
  '        scrField.set(mc, null);',
  '      }',
  '      return JSON.stringify({ success: true, message: "Screen closed via field null" });',
  '    }',
  '    return JSON.stringify({ success: false, error: "Cannot find displayGuiScreen or currentScreen field" });',
  '  }',
  '})()',
].join('\n');

/**
 * Nashorn script to click a button by ID or text.
 * Bindings required: __mcClassName__, __target__ (button id), __buttonText__ (display text for logging)
 */
export const NASHORN_CLICK_BUTTON = [
  '(function() {',
  '  var target = __target__;',
  '  var buttonText = (typeof __buttonText__ !== "undefined") ? __buttonText__ : "";',
  MC_SINGLETON_FINDER,
  '',
  FIND_CURRENT_SCREEN,
  '  if (!currentScreen) return JSON.stringify({ success: false, error: "No active GUI screen" });',
  '',
  '  // Get buttonList',
  '  var list = null;',
  '  var _lc = currentScreen.getClass();',
  '  while (_lc != null) {',
  '    var _lfs = _lc.getDeclaredFields();',
  '    for (var _li = 0; _li < _lfs.length; _li++) {',
  '      if (java.util.List.class.isAssignableFrom(_lfs[_li].getType())) {',
  '        _lfs[_li].setAccessible(true);',
  '        list = _lfs[_li].get(currentScreen);',
  '        break;',
  '      }',
  '    }',
  '    if (list) break;',
  '    _lc = _lc.getSuperclass();',
  '  }',
  '  if (!list) return JSON.stringify({ success: false, error: "buttonList not found" });',
  '',
  '  // Find matching button by ID',
  '  var targetBtn = null;',
  '  var targetId = -999;',
  '  var numericTarget = parseInt(target, 10);',
  '',
  '  for (var i = 0; i < list.size(); i++) {',
  '    var b = list.get(i);',
  '    var bc = b.getClass();',
  '    var id = -999;',
  '    var enabled = true;',
  '    while (bc != null) {',
  '      var fields = bc.getDeclaredFields();',
  '      for (var j = 0; j < fields.length; j++) {',
  '        var f = fields[j];',
  '        f.setAccessible(true);',
  '        if (f.getType() == java.lang.Integer.TYPE && id === -999) {',
  '          try { id = f.getInt(b); } catch(e) {}',
  '        }',
  '        if (f.getType() == java.lang.Boolean.TYPE) {',
  '          try { enabled = f.getBoolean(b); } catch(e) {}',
  '        }',
  '      }',
  '      bc = bc.getSuperclass();',
  '    }',
  '',
  '    if (id === numericTarget) {',
  '      targetBtn = b;',
  '      targetId = id;',
  '      if (!enabled) return JSON.stringify({ success: false, error: "Button [" + id + "] is disabled" });',
  '      break;',
  '    }',
  '  }',
  '  if (!targetBtn) return JSON.stringify({ success: false, error: "Button not found: " + target });',
  '',
  '  // Find actionPerformed method (takes 1 param assignable from button class)',
  '  var act = null;',
  '  var _ac = currentScreen.getClass();',
  '  while (_ac != null) {',
  '    var _ams = _ac.getDeclaredMethods();',
  '    for (var _ai = 0; _ai < _ams.length; _ai++) {',
  '      var _am = _ams[_ai];',
  '      if (_am.getParameterTypes().length == 1 && _am.getParameterTypes()[0].isAssignableFrom(targetBtn.getClass())) {',
  '        act = _am;',
  '        break;',
  '      }',
  '    }',
  '    if (act) break;',
  '    _ac = _ac.getSuperclass();',
  '  }',
  '  if (!act) return JSON.stringify({ success: false, error: "actionPerformed method not found" });',
  '  act.setAccessible(true);',
  '',
  FIND_SCHEDULED_TASK,
  '',
  '  if (taskMethod) {',
  '    taskMethod.setAccessible(true);',
  '    taskMethod.invoke(mc, new java.lang.Runnable({ run: function() {',
  '      try { act.invoke(currentScreen, targetBtn); } catch(e) { e.printStackTrace(); }',
  '    }}));',
  '  } else {',
  '    act.invoke(currentScreen, targetBtn);',
  '  }',
  '  return JSON.stringify({ success: true, id: targetId, text: targetText });',
  '})()',
].join('\n');
